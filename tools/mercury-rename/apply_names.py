#!/usr/bin/env python3
"""apply_names.py — write the renamed output for mercury-rename.

Reads the dump JSON (DumpFunctions.java output) plus the renamed JSON
(rename.py output) and writes two files:

1. <binary>.renamed.c — the decompiled C of every function, with each
   renamed function's old name replaced by its new name (whole-word),
   and a header comment per function carrying the summary, the
   confidence, and the old name. Functions Mercury could not name keep
   a stable sub_<address> placeholder and a needs-review flag. This is
   the file clean-room rebuilds start from.
2. ApplyNames.py — a Ghidra Python script that applies the same renames
   inside Ghidra by address:
     analyzeHeadless <projdir> <proj> -import <file.so> \
         -postScript ApplyNames <renamed.json> \
         -scriptPath <tools/mercury-rename/ghidra_scripts> -deleteProject

Usage:
  python3 apply_names.py <dump.json> <renamed.json> \
      --out-c <binary>.renamed.c --out-script ApplyNames.py
"""

from __future__ import annotations

import argparse
import json
import re
import sys

NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

GHIDRA_SCRIPT_TEMPLATE = '''# ApplyNames.py — generated by mercury-rename apply_names.py.
# Renames functions by address from a renamed JSON file.
# Run: analyzeHeadless <projdir> <proj> -import <file.so> \\
#          -postScript ApplyNames <renamed.json> \\
#          -scriptPath <tools/mercury-rename/ghidra_scripts> -deleteProject
import json
from ghidra.program.model.symbol import SourceType

renames_path = getScriptArgs()[0]
with open(renames_path, "r") as fh:
    data = json.load(fh)

renamed = 0
skipped = 0
for entry in data.get("renames", []):
    new_name = entry.get("new_name")
    if not new_name:
        skipped += 1
        continue
    try:
        addr = currentProgram.getAddressFactory().getAddress(entry["address"])
        func = getFunctionAt(addr)
        if func is None:
            printer.println("ApplyNames: no function at " + entry["address"])
            skipped += 1
            continue
        func.setName(new_name, SourceType.USER_DEFINED)
        renamed += 1
    except Exception as exc:
        printer.println("ApplyNames: failed %s -> %s: %s"
                        % (entry.get("old_name"), new_name, exc))
        skipped += 1
printer.println("ApplyNames: renamed %d, skipped %d" % (renamed, skipped))
'''


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Write renamed C + a Ghidra rename script.")
    parser.add_argument("dump", help="dump JSON from DumpFunctions.java")
    parser.add_argument("renamed", help="renamed JSON from rename.py")
    parser.add_argument("--out-c", required=True,
                        help="renamed C output file")
    parser.add_argument("--out-script", required=True,
                        help="Ghidra ApplyNames.py output file")
    args = parser.parse_args(argv)

    with open(args.dump, "r", encoding="utf-8") as fh:
        dump = json.load(fh)
    with open(args.renamed, "r", encoding="utf-8") as fh:
        renamed = json.load(fh)

    rename_by_address = {}
    for entry in renamed.get("renames", []):
        new_name = entry.get("new_name")
        if not new_name or not NAME_RE.match(new_name):
            print("WARNING: skipping invalid name %r for %s"
                  % (new_name, entry.get("address")), file=sys.stderr)
            continue
        rename_by_address[entry["address"]] = entry

    # Whole-word replacement map (old name -> new name) for every rename.
    replace_map = {}
    for function in dump.get("functions", []):
        entry = rename_by_address.get(function["address"])
        if entry:
            replace_map[function["name"]] = entry["new_name"]

    def substitute(text):
        if not replace_map:
            return text
        pattern = re.compile(
            r"\b(%s)\b" % "|".join(re.escape(old) for old in replace_map))
        return pattern.sub(lambda m: replace_map[m.group(1)], text)

    binary = dump.get("binary", "?")
    lines = [
        "/* Renamed decompilation of %s" % binary,
        " * Generated by mercury-rename (Ghidra + Mercury 3).",
        " * Names are AI proposals, NOT the original source names.",
        " * Functions Mercury could not name carry a sub_<address>",
        " * placeholder and a NEEDS-REVIEW flag. Verify every name",
        " * against the code before reusing it in a rebuild.",
        " */",
        "",
    ]
    renamed_count = 0
    for function in dump.get("functions", []):
        entry = rename_by_address.get(function["address"])
        code = function.get("decompiled_c") or ""
        if not function.get("decompile_ok") or not code:
            lines.append("/* %s at %s — NOT DECOMPILED, no C to rename */"
                         % (function["name"], function["address"]))
            lines.append("")
            continue
        if entry:
            renamed_count += 1
            flag = " NEEDS-REVIEW" if entry.get("needs_review") else ""
            lines.append("/* %s%s" % (entry["new_name"], flag))
            lines.append(" * was: %s at %s" % (function["name"],
                                               function["address"]))
            lines.append(" * %s" % (entry.get("summary") or ""))
            lines.append(" * confidence: %.2f (model: %s)"
                         % (entry.get("confidence", 0.0),
                            renamed.get("model", "?")))
            lines.append(" */")
        else:
            lines.append("/* %s at %s — unchanged (already named) */"
                         % (function["name"], function["address"]))
        lines.append(substitute(code))
        lines.append("")

    with open(args.out_c, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    with open(args.out_script, "w", encoding="utf-8") as fh:
        fh.write(GHIDRA_SCRIPT_TEMPLATE)
    print("wrote %s (%d functions renamed in C)" % (args.out_c, renamed_count))
    print("wrote %s (Ghidra rename script, %d renames)"
          % (args.out_script, len(rename_by_address)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
